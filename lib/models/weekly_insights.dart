class WeeklySummary {
  final double avgProductivity;
  final double avgEnergy;
  final double avgWorkLifeBalance;
  final double avgIsolation;
  final double avgTotalHours;
  final double totalOvertimeHours;

  WeeklySummary({
    required this.avgProductivity,
    required this.avgEnergy,
    required this.avgWorkLifeBalance,
    required this.avgIsolation,
    required this.avgTotalHours,
    required this.totalOvertimeHours,
  });
}